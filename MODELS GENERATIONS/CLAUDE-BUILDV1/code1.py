from collections import Counter

# --- [KEEPING YOUR ENCODERS EXACTLY AS THEY WERE] ---

def encode_momentum(momentum):
    return "L-" + "".join([str(momentum.get(k, "x")) for k in [
        "momentum_state", "momentum_slope_zone", "entry_bias"
    ]])

def encode_breakout(breakout):
    return "-B" + "".join([str(breakout.get(k, "x")) for k in [
        "squeeze_state", "breakout_bias", "entry_viability"
    ]])

def encode_vwap(vwap):
    return "-V" + "".join([str(vwap.get(k, "x")) for k in [
        "vwap_zone", "is_above_vwap", "volume_pressure", "liquidity_structure"
    ]])

def encode_micro(micro):
    return "-X" + "".join([str(micro.get(k, "x")) for k in [
        "micro_risk_zone", "burst_type", "tail_pressure_direction"
    ]])

def encode_candle(candle):
    return "-C" + "".join([str(candle.get(k, "x")) for k in [
        "sequence_type", "candle_dominance", "pattern_strength"
    ]])

def build_condition_code(momentum, breakout, vwap, micro, candle):
    return (
        encode_momentum(momentum) +
        encode_breakout(breakout) +
        encode_vwap(vwap) +
        encode_micro(micro) +
        encode_candle(candle)
    )

# --- [MATCH SCORING — UNCHANGED LOGIC, SAFER BOUNDS] ---

def _get_clean_data(code):
    for char in ["L", "B", "V", "X", "C", "-"]:
        code = code.replace(char, "")
    return code

def calculate_match_score(pattern, signature):
    p_data = _get_clean_data(pattern)
    s_data = _get_clean_data(signature)

    total_slots = min(len(p_data), len(s_data))
    matches = 0
    pattern_legit = 0

    for p, s in zip(p_data[:total_slots], s_data[:total_slots]):
        if p != "x":
            pattern_legit += 1
            if p == s:
                matches += 1

    if pattern_legit == 0:
        return 0.0

    precision = matches / pattern_legit
    significance = pattern_legit / total_slots
    return round(precision * significance, 4)

# --- [REBUILT MARKET EVALUATION — HIERARCHICAL + CONSENSUS FALLBACK] ---

def evaluate_market_state(momentum, breakout, micro, vwap, candle, conditions):
    """
    REBUILT:
    - Best match decides FIRST
    - Consensus always calculated
    - Consensus used ONLY if best match = hold / no_trade
    """

    condition_code = build_condition_code(momentum, breakout, vwap, micro, candle)

    # 1. Score all patterns
    scored_matches = []
    for pattern, meta in conditions.items():
        score = calculate_match_score(pattern, condition_code)
        if score > 0:
            data = meta.copy()
            data["match_score"] = score
            data["matched_pattern"] = pattern
            scored_matches.append(data)

    if not scored_matches:
        return {
            "condition_code": condition_code,
            "final_bias": "no_trade",
            "confidence": 0.0,
            "entry_viability": "low",
            "meaning": "No market alignment found.",
            "consensus_used": False,
            "consensus_count": 0
        }

    # 2. Rank matches
    scored_matches.sort(key=lambda x: x["match_score"], reverse=True)
    top_5 = scored_matches[:5]
    best_match = top_5[0]

    # 3. Always calculate consensus
    biases = [m["final_bias"] for m in top_5]
    counts = Counter(biases)
    consensus_bias, consensus_freq = counts.most_common(1)[0]

    # 4. Decision Logic (STRICT AS REQUESTED)

    # Case A: Best match is actionable → trust it fully
    if best_match["final_bias"] not in ("hold", "no_trade"):
        return {
            "condition_code": condition_code,
            "condition_id": best_match["condition_id"],
            "final_bias": best_match["final_bias"],
            "confidence": best_match["match_score"],
            "entry_viability": best_match["entry_viability"],
            "meaning": f"Best match override: {best_match['meaning']}",
            "consensus_used": False,
            "consensus_count": 1
        }

    # Case B: Best match is HOLD / NO_TRADE → fallback to consensus
    if consensus_bias not in ("hold", "no_trade") and consensus_freq >= 3:
        avg_conf = round(
            sum(m["match_score"] for m in top_5 if m["final_bias"] == consensus_bias) / consensus_freq,
            4
        )
        return {
            "condition_code": condition_code,
            "condition_id": best_match["condition_id"],
            "final_bias": consensus_bias,
            "confidence": avg_conf,
            "entry_viability": best_match["entry_viability"],
            "meaning": f"Consensus fallback ({consensus_freq}/5): {best_match['meaning']}",
            "consensus_used": True,
            "consensus_count": consensus_freq
        }

    # Case C: Hold confirmed
    return {
        "condition_code": condition_code,
        "condition_id": best_match["condition_id"],
        "final_bias": "no_trade",
        "confidence": 0.0,
        "entry_viability": "low",
        "meaning": "Hold confirmed: best match neutral and no strong consensus.",
        "consensus_used": True,
        "consensus_count": consensus_freq
    }
